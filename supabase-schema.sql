-- HJ Shop database setup for Supabase
-- 1) Create a Supabase project.
-- 2) Create an Auth user (email/password) in Authentication > Users.
-- 3) Run this SQL.
-- 4) Replace the values in supabase-config.js.

create table if not exists public.site_settings (
  id bigint primary key default 1,
  site_name text default 'HJ SHOP', logo_text text default 'HJ', topbar text default '🚚 দ্রুত ডেলিভারি • Cash on Delivery',
  whatsapp text default '01320939359', facebook text default '',
  hero_eyebrow text default 'WELCOME TO HJ SHOP', hero_title text default 'Smart products.<br><span>Better everyday.</span>', hero_text text default '', hero_button text default 'Shop Now →', hero_image text default '',
  banner_eyebrow text default 'HJ SPECIAL', banner_title text default 'Find something useful today.', banner_text text default '', banner_button text default 'Explore Products', banner_image text default '',
  about_title text default 'Simple shopping, honest service.', about_text text default '', contact_text text default '',
  dhaka_delivery numeric default 80, outside_delivery numeric default 150
);
insert into public.site_settings (id) values (1) on conflict (id) do nothing;

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null, category text not null, price numeric not null default 0, old_price numeric default 0,
  image text default '', description text default '', stock integer default 0, created_at timestamptz default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(), customer_name text not null, phone text not null, district text,
  address text, delivery_area text, payment text, items jsonb, total numeric default 0,
  status text default 'pending', created_at timestamptz default now()
);

create table if not exists public.admins (user_id uuid primary key references auth.users(id) on delete cascade);

alter table public.site_settings enable row level security;
alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.admins enable row level security;

create or replace function public.is_admin() returns boolean language sql security definer set search_path=public as $$
  select exists(select 1 from public.admins where user_id=auth.uid());
$$;

-- Public storefront can read settings/products.
create policy "public read settings" on public.site_settings for select using (true);
create policy "public read products" on public.products for select using (true);
-- Customers can submit orders; only admins can read/update/delete orders.
create policy "public create orders" on public.orders for insert with check (true);
create policy "admin read orders" on public.orders for select using (public.is_admin());
create policy "admin update orders" on public.orders for update using (public.is_admin());
create policy "admin delete orders" on public.orders for delete using (public.is_admin());
-- Only admins can change products/settings.
create policy "admin write settings" on public.site_settings for all using (public.is_admin()) with check (public.is_admin());
create policy "admin write products" on public.products for all using (public.is_admin()) with check (public.is_admin());
-- Admin list itself: a user can only see their own membership.
create policy "admin self read" on public.admins for select using (user_id=auth.uid());

